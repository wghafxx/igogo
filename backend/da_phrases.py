RECENT_WINDOW = 5


async def pick_phrase(db, choice):
    # Not among the last 5 issued and not held by another request still waiting for review.
    recent = await db.deposits.find({"payment_method": "donationalerts", "da_phrase": {"$exists": True}}, {"_id": 0, "da_phrase": 1}) \
        .sort("created_at", -1).limit(RECENT_WINDOW).to_list(RECENT_WINDOW)
    active = await db.deposits.distinct("da_phrase", {"payment_method": "donationalerts", "status": "pending"})
    taken = {r["da_phrase"] for r in recent} | set(active)
    return choice([p for p in PHRASES if p not in taken] or PHRASES)
