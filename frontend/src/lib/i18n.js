const KEY = "bloxgrade_lang";

export const getLang = () => {
  try {
    const v = localStorage.getItem(KEY);
    if (v === "ru" || v === "en") return v;
    if ((navigator.language || "").toLowerCase().startsWith("en")) return "en";
  } catch { /* ignore */ }
  return "ru";
};

export const dateLocale = (lang) => (lang === "en" ? "en-US" : "ru-RU");

export const fmtDT = (d, lang) => {
  try {
    return new Date(d).toLocaleString(dateLocale(lang), { day: "2-digit", month: "2-digit", hour: "2-digit", minute: "2-digit" });
  } catch {
    return "";
  }
};

